let currentLang = localStorage.getItem('palm-lang') || 'en';

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('palm-lang', lang);
  document.documentElement.lang = lang === 'am' ? 'am' : 'en';

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang][key]) {
      if (el.tagName === 'INPUT' && el.type === 'submit') {
        el.value = translations[lang][key];
      } else if (el.tagName === 'INPUT' && el.placeholder !== undefined) {
        el.placeholder = translations[lang][key];
      } else {
        el.textContent = translations[lang][key];
      }
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (translations[lang][key]) el.placeholder = translations[lang][key];
  });

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  document.querySelectorAll('[data-lang-only]').forEach(el => {
    el.style.display = el.getAttribute('data-lang-only') === lang ? '' : 'none';
  });

  window.dispatchEvent(new Event('palm-lang-change'));
}

document.addEventListener('DOMContentLoaded', () => setLanguage(currentLang));
